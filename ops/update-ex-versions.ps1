<#
.SYNOPSIS
    Recompute the composed version of every EX fork in this workspace.

.DESCRIPTION
    Each EX repository tracks VERSION at its root as "{source}+{ex}":

        source  newest source-repository tag, without the leading "v"
                (CLIProxyAPI v8.0.76 -> 8.0.76)
        ex      this fork's own semantic version, e.g. 1.0.3

    Composing them gives a version such as "8.0.76+1.0.3": the semver build
    metadata keeps the upstream release visible while the fork's own history
    stays orderable.

    The script rewrites VERSION plus the generated Go constant that plain
    `go build` compiles, so a source merge never leaves a stale version behind.
    The generated file is guarded by a test in every repository.

.PARAMETER Root
    Workspace root that contains the EX repositories and this ops directory.

.PARAMETER BumpEx
    Bump the fork part before composing: patch, minor or major.

.PARAMETER ExVersion
    Set the fork part explicitly, for example 1.0.3. Overrides -BumpEx.

.PARAMETER Repository
    Restrict the run to specific repository directory names.

.PARAMETER DryRun
    Report the composed versions without writing any file.

.EXAMPLE
    .\ops\update-ex-versions.ps1
    Refresh the source part of every fork after merging upstream.

.EXAMPLE
    .\ops\update-ex-versions.ps1 -BumpEx patch
    Ship a fork change: 8.0.76+1.0.2 -> 8.0.76+1.0.3.
#>
[CmdletBinding()]
param(
    [string]$Root = 'D:\WILL\AGENT\CPA',
    [ValidateSet('none', 'patch', 'minor', 'major')][string]$BumpEx = 'none',
    [string]$ExVersion = '',
    [string[]]$Repository = @(),
    [switch]$DryRun
)

$ErrorActionPreference = 'Stop'
$rootPath = [IO.Path]::GetFullPath($Root)
$semverPattern = '^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$'
$defaultExVersion = '1.0.0'

$definitions = @(
    [ordered]@{
        Name      = 'CPA-Core-ex'
        Source    = 'origin/main'
        Generated = 'cmd\server\version_generated.go'
        Package   = 'main'
        Constant  = 'generatedVersion'
    },
    [ordered]@{
        Name      = 'CPA-Manager-Plus-ex'
        Source    = 'origin/main'
        Generated = 'apps\manager-server\internal\buildinfo\version_generated.go'
        Package   = 'buildinfo'
        Constant  = 'generatedVersion'
    },
    [ordered]@{
        Name      = 'CPA-OpenCode-ex'
        Source    = 'origin/main'
        Generated = 'internal\plugin\version_generated.go'
        Package   = 'plugin'
        Constant  = 'generatedVersion'
    },
    [ordered]@{
        Name      = 'CPA-Usage-Keeper-ex'
        Source    = 'upstream/main'
        Generated = 'internal\version\version_generated.go'
        Package   = 'version'
        Constant  = 'generatedVersion'
    }
)

if ($Repository.Count -gt 0) {
    $unknown = @($Repository | Where-Object { $name = $_; -not ($definitions | Where-Object { $_.Name -eq $name }) })
    if ($unknown.Count -gt 0) {
        throw "Unknown EX repository: $($unknown -join ', ')"
    }
    $definitions = @($definitions | Where-Object { $Repository -contains $_.Name })
}

if ($ExVersion) {
    if ($ExVersion -notmatch $semverPattern) {
        throw "ExVersion must be major.minor.patch, got '$ExVersion'"
    }
}


function Split-ComposedVersion([string]$Value, [string]$Name) {
    $trimmed = $Value.Trim()
    $parts = $trimmed.Split('+')
    if ($parts.Count -ne 2 -or $parts[0] -notmatch $semverPattern -or $parts[1] -notmatch $semverPattern) {
        throw "$Name VERSION must be 'major.minor.patch+major.minor.patch', got '$trimmed'"
    }
    return [pscustomobject]@{ Source = $parts[0]; Ex = $parts[1] }
}

function Get-SourceVersion([string]$RepositoryPath, [string]$Name, [string]$SourceRef) {
    $tag = (& git -C $RepositoryPath describe --tags --abbrev=0 $SourceRef 2>$null)
    if ($LASTEXITCODE -ne 0 -or -not $tag) {
        throw "$Name has no source tag reachable from $SourceRef; fetch the source remote first"
    }
    $version = $tag.Trim() -replace '^v', ''
    if ($version -notmatch $semverPattern) {
        throw "$Name source tag '$($tag.Trim())' is not a semantic version"
    }
    return $version
}

function Step-ExVersion([string]$Current, [string]$Bump) {
    if ($Bump -eq 'none' -or -not $Current) {
        return $Current
    }
    $parts = @($Current.Split('.') | ForEach-Object { [int]$_ })
    switch ($Bump) {
        'major' { return ('{0}.0.0' -f ($parts[0] + 1)) }
        'minor' { return ('{0}.{1}.0' -f $parts[0], ($parts[1] + 1)) }
        'patch' { return ('{0}.{1}.{2}' -f $parts[0], $parts[1], ($parts[2] + 1)) }
    }
    throw "Unsupported bump: $Bump"
}

function Write-GeneratedVersion([string]$Path, [string]$Package, [string]$Constant, [string]$Composed, [string]$SourceRef) {
    $content = @(
        '// Code generated by ops/update-ex-versions.ps1; DO NOT EDIT.'
        '//'
        "// Composed release identity: {source}+{ex}, where the source part is the"
        "// newest tag reachable from $SourceRef and the ex part is this fork's own"
        '// semantic version. Re-run the script after merging the source repository.'
        ''
        "package $Package"
        ''
        "// $Constant is the composed version compiled into ordinary builds."
        "const $Constant = `"$Composed`""
        ''
    ) -join "`n"
    [IO.File]::WriteAllText($Path, $content, (New-Object Text.UTF8Encoding($false)))
}

$rows = @()
foreach ($definition in $definitions) {
    $repositoryPath = Join-Path $rootPath $definition.Name
    if (-not (Test-Path -LiteralPath $repositoryPath -PathType Container)) {
        throw "Missing repository: $repositoryPath"
    }
    $versionPath = Join-Path $repositoryPath 'VERSION'
    $generatedPath = Join-Path $repositoryPath $definition.Generated

    if (-not (Test-Path -LiteralPath $generatedPath -PathType Leaf)) {
        throw "$($definition.Name) is missing the generated source $($definition.Generated); wire the constant before composing versions"
    }

    $current = $null
    if (Test-Path -LiteralPath $versionPath -PathType Leaf) {
        $current = Split-ComposedVersion -Value ([IO.File]::ReadAllText($versionPath)) -Name $definition.Name
    }

    if ($ExVersion) {
        $ex = $ExVersion
    }
    elseif ($current) {
        $ex = Step-ExVersion -Current $current.Ex -Bump $BumpEx
        if (-not $ex) { $ex = $defaultExVersion }
    }
    else {
        $ex = $defaultExVersion
    }

    $source = Get-SourceVersion -RepositoryPath $repositoryPath -Name $definition.Name -SourceRef $definition.Source
    $composed = "$source+$ex"

    $note = ''
    if ($current -and $current.Source -ne $source) {
        $note = "source $($current.Source) -> $source"
    }
    elseif ($current -and $current.Ex -ne $ex) {
        $note = "ex $($current.Ex) -> $ex"
    }
    elseif ($current) {
        $note = 'unchanged'
    }
    else {
        $note = 'initialized'
    }

    if (-not $DryRun) {
        [IO.File]::WriteAllText($versionPath, "$composed`n", (New-Object Text.UTF8Encoding($false)))
        Write-GeneratedVersion -Path $generatedPath -Package $definition.Package -Constant $definition.Constant -Composed $composed -SourceRef $definition.Source
    }

    $rows += [pscustomobject]@{
        Repository = $definition.Name
        Version    = $composed
        Change     = $note
        Written    = (-not $DryRun)
    }
}

$rows | Format-Table -AutoSize
if ($DryRun) {
    Write-Output 'Dry run: no file was written.'
}
